_LONGEST_FIRST = sorted(HINDI_ITEMS, key=lambda name: -len(HINDI_ITEMS[name]))


def hindi_item(name: str) -> str:
    return HINDI_ITEMS.get(name, name)


def item_named_in(question: str) -> str | None:
    """The item a Hindi sentence names, by its saved English name. The longest name wins, so
    "दूध ब्रेड" is not "दूध"."""
    return next((name for name in _LONGEST_FIRST if HINDI_ITEMS[name] in question), None)
