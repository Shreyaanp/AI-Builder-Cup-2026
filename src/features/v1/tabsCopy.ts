/**
 * Menu or services, by what the shop is (personalization). Cheap: the category text the owner
 * already gave. Anything not clearly a service keeps "Menu".
 */
const SERVICE_WORDS =
  /salon|barber|hair|beauty|nail|spa|massage|tailor|laundry|repair|clinic|tuition|tutor|fitness|gym|studio|cleaning|photograph/i
export function isServiceShop(category: string | undefined) {
  return SERVICE_WORDS.test(category ?? '')
}
