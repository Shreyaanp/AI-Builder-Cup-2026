/**
 * Menu or services, by what the shop is (personalization). Cheap: the category text the owner
 * already gave. Anything not clearly a service keeps "Menu".
 */
const SERVICE_WORDS =
  /salon|barber|hair|beauty|nail|spa|massage|tailor|laundry|repair|clinic|tuition|tutor|fitness|gym|studio|cleaning|photograph/i
export function isServiceShop(category: string | undefined) {
  return SERVICE_WORDS.test(category ?? '')
}

/** Shops that resell goods: "Menu" and a samosa example mean nothing to a minimart. */
const RETAIL_WORDS =
  /mini ?mart|supermarket|hypermarket|grocer|kirana|provision|general store|department|pharmacy|chemist|hardware|stationery|wholesal|distribut|किराना|जनरल स्टोर/i

/** The word for the shop's list of things: Menu, Services or Products. */
export function listWord(
  category: string | undefined,
  menu: string,
  tabs: { services: string; products: string },
) {
  if (isServiceShop(category)) return tabs.services
  return RETAIL_WORDS.test(category ?? '') ? tabs.products : menu
}
